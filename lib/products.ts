const EMOJI_PATTERN =
  /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}\u{FE0F}]/gu;

// The stored `description` is the verbatim Etsy listing copy — long,
// multi-paragraph, emoji-heavy, meant for the page body. Meta descriptions
// need something short and plain: just the opening paragraph, emojis
// stripped, collapsed to one line, and capped at a length search engines
// won't truncate mid-sentence.
export function getMetaDescription(product: Product, maxLength = 160): string {
  const firstParagraph = product.description.split(/\n\s*\n/)[0];
  const cleaned = firstParagraph.replace(EMOJI_PATTERN, "").replace(/\s+/g, " ").trim();
  if (cleaned.length <= maxLength) return cleaned;
  const truncated = cleaned.slice(0, maxLength);
  const lastSpace = truncated.lastIndexOf(" ");
  return `${truncated.slice(0, lastSpace > 0 ? lastSpace : maxLength)}…`;
}
